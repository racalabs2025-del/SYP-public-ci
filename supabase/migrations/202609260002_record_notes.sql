create table if not exists public.record_notes (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text not null,
  note text not null check (char_length(note) between 1 and 4000),
  author_id text not null,
  author_label text not null,
  created_at timestamptz not null default now()
);
alter table public.record_notes enable row level security;
create index if not exists record_notes_lookup on public.record_notes(table_name, record_id, created_at desc);
drop policy if exists record_notes_read on public.record_notes;
create policy record_notes_read on public.record_notes for select to authenticated using (public.current_role() in ('admin','manager','chief','data_entry','viewer'));
drop policy if exists record_notes_insert on public.record_notes;
create policy record_notes_insert on public.record_notes for insert to authenticated with check (public.current_role() in ('admin','manager','chief') and author_id = auth.uid()::text);
